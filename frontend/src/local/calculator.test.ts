const calc = (expr: string) => calculate(expr).result;

function error(expr: string): string {
  try {
    calculate(expr);
  } catch (e) {
    expect(e).toBeInstanceOf(CalcError);
    return (e as Error).message;
  }
  throw new Error(`${expr} did not fail`);
}

