// ---------------------------------------------------------------- exactness

function isqrt(n: bigint): bigint {
  if (n < 2n) return n;
  let x = n;
  let y = (x + 1n) / 2n;
  while (y < x) {
    x = y;
    y = (x + n / x) / 2n;
  }
  return x;
}

describe("exactness", () => {
  it("does rational arithmetic exactly", () => {
    const rng = new Random(7);
    for (let i = 0; i < 300; i++) {
      const a = new Fraction(rng.randint(-50, 50), rng.randint(1, 20));
      const b = new Fraction(rng.randint(-50, 50), rng.randint(1, 20));
      const op = rng.choice(["+", "-", "*", "/"]);
      if (op === "/" && b.n === 0n) continue;
      const want = op === "+" ? a.add(b) : op === "-" ? a.sub(b) : op === "*" ? a.mul(b) : a.div(b);
      expect(calc(`(${a}) ${op} (${b})`)).toBe(want.toString());
    }
    expect(calc("(2/3)**20")).toBe("1048576/3486784401");
    expect(calc("1/3 + 1/3 + 1/3")).toBe("1");
  });

  it("floors irrational numbers exactly, even next to a whole number", () => {
    for (const k of [0, 5, 20, 100, 500]) {
      expect(calc(`floor(10**${k} * sqrt(2))`)).toBe(isqrt(2n * 10n ** BigInt(2 * k)).toString());
    }
    // (1 + sqrt(2))**n = a + b*sqrt(2) is within 10**-(digits) of a whole number
    for (const n of [10, 100, 200, 1000, 3000, 10000]) {
      let a = 1n;
      let b = 0n;
      for (let i = 0; i < n; i++) [a, b] = [a + 2n * b, a + b];
      const floor = a + isqrt(2n * b * b);
      expect(calc(`floor((1+sqrt(2))**${n}) % 10**12`), `n = ${n}`).toBe((floor % 10n ** 12n).toString());
      expect(calc(`ceiling((1+sqrt(2))**${n}) - floor((1+sqrt(2))**${n})`)).toBe("1");
    }
    expect(calc("floor(E**(pi*sqrt(163)))")).toBe("262537412640768743"); // 0.99999999999925 below an integer
  });

  it("recognises equal numbers in different forms", () => {
    expect(calc("sqrt(2) == 2**0.5")).toBe("True");
    expect(calc("2**(1/3)*2**(1/3)*2**(1/3) == 2")).toBe("True");
    expect(calc("sqrt(3+2*sqrt(2)) == 1+sqrt(2)")).toBe("True"); // a nested root that denests
    expect(calc("(2+2*pi)/(1+pi)")).toBe("2");
    expect(calc("sqrt(pi)*sqrt(pi)")).toBe("pi  (approximately 3.14159265358979)");
    expect(calc("pi - 355/113 < 0")).toBe("True"); // 355/113 = 3.1415929...
    expect(calc("sqrt(2) < 99/70")).toBe("True");
  });

  it("agrees with brute force on number theory", () => {
    const sieve = new Uint8Array(20001).fill(1);
    sieve[0] = sieve[1] = 0;
    for (let i = 2; i * i <= 20000; i++) if (sieve[i]) for (let j = i * i; j <= 20000; j += i) sieve[j] = 0;
    const primes: number[] = [];
    for (let i = 2; i <= 20000; i++) if (sieve[i]) primes.push(i);
    for (let n = -5; n <= 2000; n++) expect(isPrimeBig(BigInt(n)), String(n)).toBe(n >= 0 && sieve[n] === 1);
    for (const k of [1, 2, 3, 10, 100, 1000, primes.length]) expect(calc(`prime(${k})`)).toBe(String(primes[k - 1]));
    for (const n of [0, 1, 2, 3, 10, 97, 100, 1000, 9973, 20000]) expect(calc(`primepi(${n})`)).toBe(String(primes.filter((p) => p <= n).length));
    const rng = new Random(11);
    for (let i = 0; i < 60; i++) {
      const n = rng.randint(1, 5000);
      const divs = Array.from({ length: n }, (_, j) => j + 1).filter((d) => n % d === 0);
      expect(calc(`divisors(${n})`)).toBe(`[${divs.join(", ")}]`);
      const fac = calc(`factorint(${n})`);
      const pairs = fac === "{}" ? [] : fac.slice(1, -1).split(", ").map((s) => s.split(": ").map(Number));
      expect(pairs.reduce((acc, [p, e]) => acc * p ** e, 1)).toBe(n);
      for (const [p] of pairs) expect(sieve[p]).toBe(1);
    }
    let row = [1n];
    for (let n = 0; n <= 40; n++) {
      for (const k of [0, 1, Math.floor(n / 2), n]) expect(calc(`binomial(${n}, ${k})`)).toBe(String(k <= n ? row[k] : 0n));
      row = [1n, ...row.slice(1).map((v, i) => v + row[i]), 1n];
    }
  });
});

